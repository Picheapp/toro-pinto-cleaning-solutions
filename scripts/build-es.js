// Merges scripts/es/*.json into public/js/es.js (the Spanish dictionary).
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, 'es'); const out = {};
for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.json')).sort()) Object.assign(out, JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')));
const lines = Object.entries(out).sort(([a], [b]) => a.localeCompare(b)).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`);
fs.writeFileSync(path.join(__dirname, '..', 'public', 'js', 'es.js'), `// Spanish (Puerto Rico) dictionary. Keys are the English UI strings. Generated by scripts/build-es.js from scripts/es/*.json.\nexport const ES = {\n${lines.join('\n')}\n};\n`);
console.log(Object.keys(out).length + ' translations');
