const PATTERNS = [
  [/^(.+) is required$/, (m) => `${m[1]} es obligatorio`],
  [/^Only (\d+) left of (.+)$/, (m) => `Solo quedan ${m[1]} de ${m[2]}`],
  [/^That code needs a minimum of (.+)$/, (m) => `Ese código requiere un mínimo de ${m[1]}`],
  [/^That code only applies to (.+)$/, (m) => `Ese código solo aplica a ${m[1] === 'services' ? 'servicios' : 'productos'}`],
  [/^Minimum redemption is (\d+) points$/, (m) => `El mínimo para canjear es ${m[1]} puntos`],
  [/^Payment exceeds the balance due \((.+)\)$/, (m) => `El pago excede el balance pendiente (${m[1]})`],
  [/^This service is only available for (.+) properties$/, (m) => `Este servicio solo está disponible para propiedades ${m[1] === 'residential' ? 'residenciales' : 'comerciales'}`],
];
function tr(msg, lang) {
  if (lang !== 'es' || !msg) return msg;
  if (EXACT[msg]) return EXACT[msg];
  for (const [re, f] of PATTERNS) { const m = re.exec(msg); if (m) return f(m); }
  return msg;
}
